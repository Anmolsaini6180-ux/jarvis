def _schedule_windows(target_dt: datetime, task_name: str,
                      script_path: Path, message: str) -> str:
    python_exe = Path(sys.executable)
    pythonw = python_exe.parent / "pythonw.exe"
    if pythonw.exists():
        python_exe = pythonw

    xml_path = _scripts_dir() / f"{task_name}.xml"
    xml_content = (
        '<?xml version="1.0" encoding="UTF-16"?>\n'
        '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">\n'
        '  <RegistrationInfo><Description>J.A.R.V.I.S Reminder</Description></RegistrationInfo>\n'
        '  <Triggers><TimeTrigger>\n'
        f'    <StartBoundary>{target_dt.isoformat(timespec="seconds")}</StartBoundary>\n'
        '    <Enabled>true</Enabled>\n'
        '  </TimeTrigger></Triggers>\n'
        '  <Actions><Exec>\n'
        f'    <Command>{escape(str(python_exe))}</Command>\n'
        f'    <Arguments>"{escape(str(script_path))}"</Arguments>\n'
        '  </Exec></Actions>\n'
        '  <Settings>\n'
        '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>\n'
        '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>\n'
        '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>\n'
        '    <StartWhenAvailable>true</StartWhenAvailable>\n'
        '    <ExecutionTimeLimit>PT5M</ExecutionTimeLimit>\n'
        '    <Enabled>true</Enabled>\n'
        '  </Settings>\n'
        '  <Principals><Principal>\n'
        '    <LogonType>InteractiveToken</LogonType>\n'
        '    <RunLevel>LeastPrivilege</RunLevel>\n'
        '  </Principal></Principals>\n'
        '</Task>'
    )

    xml_path.write_text(xml_content, encoding="utf-16")

    result = subprocess.run(
        ["schtasks", "/Create", "/TN", task_name, "/XML", str(xml_path)],
        capture_output=True, text=True, timeout=15, **_CNW,
    )

    try:
        xml_path.unlink(missing_ok=True)
    except Exception:
        pass

    if result.returncode != 0:
        script_path.unlink(missing_ok=True)
        err = (result.stderr or result.stdout).strip()
        print(f"[Reminder] ❌ schtasks: {err}")
        raise RuntimeError("Task Scheduler refused the reminder: "+err[:200])

    return task_name


def _schedule_mac(target_dt: datetime, task_name: str,
                  script_path: Path) -> str:
    agents_dir = Path.home() / "Library" / "LaunchAgents"
    agents_dir.mkdir(parents=True, exist_ok=True)

    label     = f"com.jarvis.reminder.{task_name}"
    plist_path = agents_dir / f"{label}.plist"

    plist_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>             <string>{label}</string>
  <key>ProgramArguments</key>
  <array>
    <string>{escape(sys.executable)}</string>
    <string>{escape(str(script_path))}</string>
  </array>
  <key>StartCalendarInterval</key>
  <dict>
      <key>Month</key>  <integer>{target_dt.month}</integer>
    <key>Day</key>    <integer>{target_dt.day}</integer>
    <key>Hour</key>   <integer>{target_dt.hour}</integer>
    <key>Minute</key> <integer>{target_dt.minute}</integer>
  </dict>
  <key>RunAtLoad</key>         <false/>
  <key>StandardOutPath</key>   <string>/dev/null</string>
  <key>StandardErrorPath</key> <string>/dev/null</string>
</dict>
</plist>
"""
    plist_path.write_text(plist_content, encoding="utf-8")
    plist_path.chmod(0o644)

    result = subprocess.run(
        ["launchctl", "load", str(plist_path)],
        capture_output=True, text=True, timeout=15,
    )

    if result.returncode != 0:
        plist_path.unlink(missing_ok=True)
        script_path.unlink(missing_ok=True)
        print(f"[Reminder] ❌ launchctl: {result.stderr.strip()}")
        raise RuntimeError("launchctl refused reminder: "+result.stderr.strip()[:200])

    return label


def _schedule_linux(target_dt: datetime, task_name: str,
                    script_path: Path) -> str:

    if shutil.which("systemd-run"):
        on_calendar = target_dt.strftime("%Y-%m-%d %H:%M:00")
        result = subprocess.run(
            [
                "systemd-run",
                "--user",
                f"--on-calendar={on_calendar}",
                f"--unit={task_name}",
                "--",
                sys.executable, str(script_path),
            ],
            capture_output=True, text=True, timeout=15,
        )
        if result.returncode == 0:
            return task_name
        print(f"[Reminder] ⚠️ systemd-run failed: {result.stderr.strip()}, trying 'at'")

    if shutil.which("at"):
        at_time = target_dt.strftime("%H:%M %Y-%m-%d")
        cmd_str = shlex.join([sys.executable,str(script_path)])+"\n"
        result  = subprocess.run(
            ["at", at_time],
            input=cmd_str, capture_output=True, text=True, timeout=15,
        )
        if result.returncode == 0:
            return task_name
        print(f"[Reminder] ❌ at: {result.stderr.strip()}")
        return ""

    print("[Reminder] ❌ Neither systemd-run nor at found on this Linux system.")
    return ""

def reminder(parameters: dict,response=None,player=None,session_memory=None) -> str:
    try:
        target_dt=_parse_time(parameters.get('date',''),parameters.get('time',''),parameters.get('timezone',''))
    except (ValueError,KeyError) as e:return f'Invalid reminder time: {e}'
    if target_dt<=datetime.now().astimezone():return 'Reminder time has already passed.'
    message=parameters.get('message','Reminder').strip()
    if not message or len(message)>2000:return 'Reminder message must contain 1–2000 characters.'
    os_name=_get_os();task_name='JARVISReminder_'+uuid.uuid4().hex
    state=_base_dir()/'config/reminders.json'
    entry={'id':task_name,'time':target_dt.isoformat(),'timezone':parameters.get('timezone') or 'system local',
           'message':message,'status':'preparing'}
    storage.update(state,lambda data:data.__setitem__(task_name,entry))
    script_path=None
    try:
        script_path=_write_notify_script(task_name,message,os_name)
        local_dt=target_dt.astimezone()
        if os_name=='windows':job_id=_schedule_windows(local_dt,task_name,script_path,message)
        elif os_name=='mac':job_id=_schedule_mac(local_dt,task_name,script_path)
        else:job_id=_schedule_linux(local_dt,task_name,script_path)
        if not job_id:raise RuntimeError('No scheduler accepted the reminder; systemd user session/at may be unavailable')
        storage.update(state,lambda data:data[task_name].update(status='registered',job_id=job_id))
    except Exception as e:
        if script_path:script_path.unlink(missing_ok=True)
        storage.update(state,lambda data:data[task_name].update(status='failed',error=str(e)[:240]))
        return f'Reminder {task_name} was not registered: {e}'
    if player:player.write_log(f'Reminder {task_name} registered; private message redacted.')
    return f'Reminder registered: {task_name} at {target_dt.isoformat()}. Actual notification requires OS scheduler/device validation.'

def _parse_time(date,time_text,timezone=''):
    naive=datetime.fromisoformat(date+'T'+time_text)
    if naive.tzinfo:return naive
    if not timezone:return naive.astimezone()
    zone=ZoneInfo(timezone)
    first=naive.replace(tzinfo=zone,fold=0);second=naive.replace(tzinfo=zone,fold=1)
    if first.utcoffset()!=second.utcoffset():raise ValueError('Ambiguous/nonexistent DST time; supply an explicit UTC offset in time')
    if first.astimezone(ZoneInfo('UTC')).astimezone(zone).replace(tzinfo=None)!=naive:raise ValueError('Nonexistent local time')
    return first


